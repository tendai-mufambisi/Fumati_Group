/**
 * Writes the first two D1 migrations from the same files the site uses:
 *
 *   migrations/0001_init.sql  — tables, one per collection in src/data/collections.ts
 *   migrations/0002_seed.sql  — the shipped content in src/data/seed.ts
 *
 *   node scripts/build-seed.ts
 *
 * Run it only before the first deploy. Once 0001/0002 are applied to the live
 * database, later schema changes go in new numbered migrations written by hand.
 * Only line comments are used: D1's remote endpoint rejects block-comment chunks.
 */
import { writeFileSync } from "node:fs";

import { collections } from "../src/data/collections.ts";
import { SEED_COLLECTIONS, SEED_PROJECTS, SEED_SETTINGS } from "../src/data/seed.ts";

const q = (v: string | number | boolean) =>
  typeof v === "number"
    ? String(v)
    : typeof v === "boolean"
      ? v
        ? "1"
        : "0"
      : `'${v.replace(/'/g, "''")}'`;

/* ---------- schema ---------- */

const schema: string[] = [
  "-- Generated by scripts/build-seed.ts. Content columns are TEXT NOT NULL DEFAULT '' so a",
  "-- half-filled row never breaks the public site.",
  "",
  "CREATE TABLE settings (",
  "  key TEXT PRIMARY KEY,",
  "  value TEXT NOT NULL DEFAULT '',",
  "  updated_at TEXT NOT NULL DEFAULT (datetime('now'))",
  ");",
  "",
  "-- Failed sign-ins per IP, for rate limiting.",
  "CREATE TABLE login_attempts (",
  "  ip TEXT PRIMARY KEY,",
  "  failures INTEGER NOT NULL DEFAULT 0,",
  "  window_start INTEGER NOT NULL DEFAULT 0",
  ");",
  "",
  "-- Quote requests from the contact form.",
  "CREATE TABLE enquiries (",
  "  id INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  name TEXT NOT NULL DEFAULT '',",
  "  phone TEXT NOT NULL DEFAULT '',",
  "  email TEXT NOT NULL DEFAULT '',",
  "  service TEXT NOT NULL DEFAULT '',",
  "  location TEXT NOT NULL DEFAULT '',",
  "  budget TEXT NOT NULL DEFAULT '',",
  "  message TEXT NOT NULL DEFAULT '',",
  "  status TEXT NOT NULL DEFAULT 'New',",
  "  ip TEXT NOT NULL DEFAULT '',",
  "  created_at TEXT NOT NULL DEFAULT (datetime('now'))",
  ");",
  "CREATE INDEX enquiries_ip_created ON enquiries (ip, created_at);",
  "",
  "-- One row per project page at /projects/<slug>.",
  "CREATE TABLE projects (",
  "  id INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  slug TEXT NOT NULL UNIQUE,",
  ...[
    "title",
    "category",
    "location",
    "year",
    "client",
    "summary",
    "body",
    "scope",
    "challenge",
    "solution",
    "result",
    "cover",
    "cover_alt",
  ].map((c) => `  ${c} TEXT NOT NULL DEFAULT '',`),
  "  status TEXT NOT NULL DEFAULT 'Completed',",
  "  featured INTEGER NOT NULL DEFAULT 0,",
  "  published INTEGER NOT NULL DEFAULT 0,",
  "  position INTEGER NOT NULL DEFAULT 0,",
  "  created_at TEXT NOT NULL DEFAULT (datetime('now'))",
  ");",
  "CREATE INDEX projects_position ON projects (position, id);",
  "",
  "-- Photos, uploaded videos and video links for a project's gallery.",
  "CREATE TABLE project_media (",
  "  id INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  project_id INTEGER NOT NULL,",
  "  kind TEXT NOT NULL DEFAULT 'image' CHECK (kind IN ('image', 'video', 'embed')),",
  "  url TEXT NOT NULL DEFAULT '',",
  "  alt TEXT NOT NULL DEFAULT '',",
  "  position INTEGER NOT NULL DEFAULT 0",
  ");",
  "CREATE INDEX project_media_project ON project_media (project_id, position);",
];

for (const def of Object.values(collections)) {
  schema.push(
    "",
    `-- ${def.label}`,
    `CREATE TABLE ${def.table} (`,
    "  id INTEGER PRIMARY KEY AUTOINCREMENT,",
    ...def.fields.map((f) => `  ${f.key} TEXT NOT NULL DEFAULT '',`),
    "  hidden INTEGER NOT NULL DEFAULT 0,",
    "  position INTEGER NOT NULL DEFAULT 0,",
    "  created_at TEXT NOT NULL DEFAULT (datetime('now'))",
    ");",
    `CREATE INDEX ${def.table}_position ON ${def.table} (position, id);`,
  );
}

writeFileSync("migrations/0001_init.sql", schema.join("\n") + "\n");

/* ---------- seed ---------- */

const seed: string[] = ["-- Generated by scripts/build-seed.ts from src/data/seed.ts.", ""];

for (const [key, value] of Object.entries(SEED_SETTINGS)) {
  seed.push(
    `INSERT INTO settings (key, value) VALUES (${q(key)}, ${q(value)}) ON CONFLICT (key) DO NOTHING;`,
  );
}

for (const [name, def] of Object.entries(collections)) {
  const rows = SEED_COLLECTIONS[name] ?? [];
  const cols = def.fields.map((f) => f.key);
  rows.forEach((row, i) => {
    seed.push(
      `INSERT INTO ${def.table} (${cols.join(", ")}, position) VALUES (${cols.map((c) => q(row[c] ?? "")).join(", ")}, ${i + 1});`,
    );
  });
}

SEED_PROJECTS.forEach((p, i) => {
  const cover = p.media.find((m) => m.kind === "image");
  seed.push(
    `INSERT INTO projects (slug, title, category, location, year, client, status, summary, body, scope, challenge, solution, result, cover, cover_alt, featured, published, position) VALUES (${[
      p.slug,
      p.title,
      p.category,
      p.location,
      p.year,
      p.client,
      p.status,
      p.summary,
      p.body,
      p.scope,
      p.challenge,
      p.solution,
      p.result,
      cover?.url ?? "",
      cover?.alt ?? "",
    ]
      .map(q)
      .join(", ")}, ${q(p.featured)}, ${q(p.published)}, ${i + 1});`,
  );
  p.media.forEach((m, j) => {
    seed.push(
      `INSERT INTO project_media (project_id, kind, url, alt, position) SELECT id, ${q(m.kind)}, ${q(m.url)}, ${q(m.alt)}, ${j + 1} FROM projects WHERE slug = ${q(p.slug)};`,
    );
  });
});

writeFileSync("migrations/0002_seed.sql", seed.join("\n") + "\n");
console.log(
  `wrote migrations/0001_init.sql and migrations/0002_seed.sql (${seed.length} statements)`,
);
